import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [vue()],

  // ============================================================
  //  开发服务器配置
  // ============================================================
  server: {
    // ----------------------------------------------------------
    //  代理（proxy）—— 解决跨域的关键
    // ----------------------------------------------------------
    //  这是干什么的？先看问题：
    //    浏览器在 5173，后端在 8080，端口不同 = 不同源
    //    浏览器规定"不同源不给传数据"，所以直接请求会被拦
    //
    //  代理的思路（绕开而不是硬闯）：
    //    让浏览器只跟 5173 说话，永远不直接碰 8080。
    //    凡是路径以 /api 开头的请求，交给 Vite 服务器（它跑在 Node 上）
    //    由 Vite 在背后替我们去请求 8080，拿到数据再转交给浏览器。
    //
    //  为什么这样就不拦了？
    //    "跨域规则"是浏览器的规矩，而 Vite 服务器是 Node 程序，不是浏览器，
    //    它根本不受这条规矩约束。
    //    对浏览器来说：我从 5173 发请求，还是 5173 回数据 —— 同源，放行。
    //
    //  生活比喻：
    //    你（浏览器）想跟隔壁楼（8080）拿东西，但小区规定"不许跨楼直接交流"。
    //    代理就是找了个本楼的中介（Vite）：你只跟中介说话，
    //    中介去隔壁楼把东西取回来给你。小区规定管不到中介。
    // ----------------------------------------------------------
    proxy: {
      // 键 = 要拦截的路径前缀。所有 /api/xxx 都会被这条规则接走
      '/api': {
        // 真正要去的后端地址。
        // 用 127.0.0.1 而不是 localhost：
        //   localhost 可能被解析成 IPv6 的 ::1，个别环境会连不上，
        //   写 127.0.0.1 能明确走 IPv4，更稳
        target: 'http://127.0.0.1:8080',

        // changeOrigin: true
        //   把转发出去的请求头里的 Host 改成目标的地址。
        //   有些后端会校验请求来自哪个域名，不改可能被拒。
        //   加上它基本是配代理的标准动作
        changeOrigin: true,

        // rewrite 这里不需要：
        //   因为前端请求 /api/account/list，后端接口路径也是 /api/account/list
        //   两边前缀一样，不用改写。
        //   如果后端没有 /api 这个前缀（比如后端是 /account/list），
        //   才需要写 rewrite: (path) => path.replace(/^\/api/, '')
      },
    },
  },
})
