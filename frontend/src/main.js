import { createApp } from 'vue'
import App from './App.vue'

// ============================================================
//  关于脚手架自带的 style.css
// ============================================================
//  原本这里有一行：import './style.css'
//  现在**故意去掉了**，原因：
//    那个文件是 Vite 脚手架自带的演示样式，有 296 行，里面有
//      · font: 18px        → 全局字号，会把 Element Plus 的字撑大
//      · color-scheme: light dark → 跟着系统深色模式变，表格会变黑
//      · 各种 body/h1/button 的全局重置 → 和组件库抢样式
//    它本来是为 "Get started" 那个演示页服务的，我们换成 Element Plus 后
//    留着它只会互相打架（这类"全局样式打架"是前端很常见的坑）。
//  文件本身没删，还在 src/style.css，需要时可以再引回来。
// ============================================================

// ============================================================
//  Element Plus 组件库
// ============================================================
// 两行都必须写，缺一不可：
//   第 1 行 = 组件的"功能"（表格、按钮、卡片这些标签能用）
//   第 2 行 = 组件的"样式"（外观好看）
// 只写第 1 行不写第 2 行，页面会显示成一堆没有样式的裸标签。
import ElementPlus from 'element-plus'
import 'element-plus/dist/index.css'

// use(ElementPlus) = 把整个组件库注册到 Vue 应用里
// 注册之后，任何 .vue 文件里都能直接用 <el-table> <el-button> 这些标签，
// 不需要在每个文件里单独 import —— 这叫"全局注册"
createApp(App).use(ElementPlus).mount('#app')
